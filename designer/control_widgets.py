"""Designer control widget initialization helpers."""

from __future__ import annotations

from typing import Any

from PySide6.QtWidgets import QCheckBox, QComboBox, QDoubleSpinBox, QLabel, QLineEdit, QPushButton, QSpinBox, QWidget

from designer.layer_widgets import LayerListWidget
from designer.preview_label import PreviewLabel


def initialize_designer_control_widgets(
    owner: Any,
    *,
    font_families: list[str],
    known_stat_display: set[str],
    equalizer_color_presets: dict[str, dict[str, object]],
) -> None:
    owner.preview_label = PreviewLabel(owner if isinstance(owner, QWidget) else None)
    owner.designer_element_list = LayerListWidget()
    owner.designer_element_list.setObjectName("designerLayerList")
    owner.designer_kind_combo = QComboBox()
    owner.designer_kind_combo.addItem("Teksty", "texts")
    owner.designer_kind_combo.addItem("Statystyki", "stats")
    owner.designer_kind_combo.addItem("Obrazy", "images")
    owner.designer_kind_combo.addItem("Panele", "panels")
    owner.designer_kind_combo.addItem("Widgety", "widgets")
    owner.designer_selection_label = QLabel("Zaznacz element")

    owner.designer_id_edit = QLineEdit()
    owner.designer_x_spin = QSpinBox()
    owner.designer_x_spin.setRange(-5000, 5000)
    owner.designer_y_spin = QSpinBox()
    owner.designer_y_spin.setRange(-5000, 5000)
    owner.designer_w_spin = QSpinBox()
    owner.designer_w_spin.setRange(1, 5000)
    owner.designer_h_spin = QSpinBox()
    owner.designer_h_spin.setRange(1, 5000)
    owner.designer_z_spin = QSpinBox()
    owner.designer_z_spin.setRange(-1000, 1000)
    owner.designer_rotation_spin = QSpinBox()
    owner.designer_rotation_spin.setRange(0, 360)
    owner.designer_opacity_spin = QDoubleSpinBox()
    owner.designer_opacity_spin.setRange(0.0, 1.0)
    owner.designer_opacity_spin.setSingleStep(0.1)
    owner.designer_text_edit = QLineEdit()
    owner.designer_label_edit = QLineEdit()
    owner.designer_format_edit = QLineEdit()
    owner.designer_source_combo = QComboBox()
    owner._populate_designer_source_combo()
    owner.designer_stat_display_combo = QComboBox()
    owner.designer_stat_display_combo.addItems(
        [mode for mode in ("text", "progress", "gauge", "sparkline", "equalizer") if mode in known_stat_display]
    )
    owner.designer_stat_min_spin = QDoubleSpinBox()
    owner.designer_stat_min_spin.setRange(-999999.0, 999999.0)
    owner.designer_stat_min_spin.setDecimals(2)
    owner.designer_stat_max_spin = QDoubleSpinBox()
    owner.designer_stat_max_spin.setRange(-999999.0, 999999.0)
    owner.designer_stat_max_spin.setDecimals(2)
    owner.designer_stat_max_spin.setValue(100.0)
    owner.designer_stat_show_value_chk = QCheckBox("Pokaż wartość")
    owner.designer_color_edit = QLineEdit()
    owner.designer_label_color_edit = QLineEdit()
    owner.designer_value_color_edit = QLineEdit()
    owner.designer_track_color_edit = QLineEdit()
    owner.designer_fill_color_edit = QLineEdit()
    owner.designer_align_combo = QComboBox()
    owner.designer_align_combo.addItems(["left", "center", "right"])
    owner.designer_font_family_combo = QComboBox()
    owner.designer_font_family_combo.addItems(font_families)
    owner.designer_font_size_spin = QSpinBox()
    owner.designer_font_size_spin.setRange(6, 200)

    owner.designer_stat_stroke_width_spin = QSpinBox()
    owner.designer_stat_stroke_width_spin.setRange(0, 64)
    owner.designer_stat_stroke_width_spin.setSpecialValueText("auto")
    owner.designer_stat_stroke_width_spin.setValue(12)
    owner.designer_stat_gauge_preset_combo = QComboBox()
    owner._populate_designer_stat_gauge_preset_combo()
    owner.designer_gauge_low_edit = QLineEdit()
    owner.designer_gauge_mid_edit = QLineEdit()
    owner.designer_gauge_high_edit = QLineEdit()
    owner.designer_gauge_smooth_spin = QDoubleSpinBox()
    owner.designer_gauge_smooth_spin.setRange(0.05, 1.0)
    owner.designer_gauge_smooth_spin.setSingleStep(0.05)
    owner.designer_gauge_smooth_spin.setDecimals(2)
    owner.designer_gauge_smooth_spin.setValue(0.32)
    owner.designer_gauge_match_value_chk = QCheckBox("Kolor wartości jak łuk")
    owner.designer_gauge_match_value_chk.setChecked(True)
    owner.designer_gauge_inner_alpha_spin = QDoubleSpinBox()
    owner.designer_gauge_inner_alpha_spin.setRange(0.0, 1.0)
    owner.designer_gauge_inner_alpha_spin.setSingleStep(0.05)
    owner.designer_gauge_inner_alpha_spin.setDecimals(2)
    owner.designer_gauge_inner_alpha_spin.setValue(1.0)
    owner.designer_gauge_inner_alpha_spin.setToolTip(
        "Przezroczystość wypełnienia środka gauge (nie wpływa na łuk ani tekst)."
    )
    owner.designer_gauge_ring_spin = QSpinBox()
    owner.designer_gauge_ring_spin.setRange(40, 900)
    owner.designer_gauge_ring_spin.setSuffix(" px")
    owner.designer_gauge_ring_spin.setToolTip(
        "Średnica pierścienia (okręgu) gauge. Pole ramki (Szer./Wys. w Pozycja) powinno być większe "
        "— przy układzie „Pod gauge” lub „Z boku” zwiększ wysokość lub szerokość."
    )
    owner.designer_gauge_value_layout_combo = QComboBox()
    owner.designer_gauge_value_layout_combo.addItem("W środku pierścienia", "center")
    owner.designer_gauge_value_layout_combo.addItem("Pod spodem (wartość pod łukiem)", "below")
    owner.designer_gauge_value_layout_combo.addItem("Z boku (wartość po prawej)", "beside")

    owner.designer_sparkline_points_spin = QSpinBox()
    owner.designer_sparkline_points_spin.setRange(8, 240)
    owner.designer_sparkline_points_spin.setValue(42)
    owner.designer_sparkline_fill_opacity_spin = QDoubleSpinBox()
    owner.designer_sparkline_fill_opacity_spin.setRange(0.0, 1.0)
    owner.designer_sparkline_fill_opacity_spin.setSingleStep(0.05)
    owner.designer_sparkline_fill_opacity_spin.setDecimals(2)
    owner.designer_sparkline_fill_opacity_spin.setValue(0.18)
    owner.designer_sparkline_show_points_chk = QCheckBox("Pokaż punkt końcowy")
    owner.designer_sparkline_show_points_chk.setChecked(True)

    owner.designer_equalizer_bars_spin = QSpinBox()
    owner.designer_equalizer_bars_spin.setRange(6, 64)
    owner.designer_equalizer_bars_spin.setValue(18)
    owner.designer_equalizer_gap_spin = QSpinBox()
    owner.designer_equalizer_gap_spin.setRange(0, 16)
    owner.designer_equalizer_gap_spin.setValue(4)
    owner.designer_equalizer_mirror_chk = QCheckBox("Mirror from center")
    owner.designer_equalizer_mirror_chk.setChecked(False)
    owner.designer_equalizer_transparent_bg_chk = QCheckBox("Transparent background")
    owner.designer_equalizer_transparent_bg_chk.setChecked(True)
    owner.designer_equalizer_preset_combo = QComboBox()
    for preset_id, preset in equalizer_color_presets.items():
        owner.designer_equalizer_preset_combo.addItem(str(preset["label"]), preset_id)
    owner.designer_equalizer_threshold_spin = QDoubleSpinBox()
    owner.designer_equalizer_threshold_spin.setRange(0.0, 100.0)
    owner.designer_equalizer_threshold_spin.setDecimals(0)
    owner.designer_equalizer_threshold_spin.setSingleStep(5.0)
    owner.designer_equalizer_threshold_spin.setSuffix("%")
    owner.designer_equalizer_threshold_spin.setValue(100.0)
    owner.designer_equalizer_threshold_color_edit = QLineEdit()

    owner.widget_title_font_spin = QSpinBox()
    owner.widget_title_font_spin.setRange(6, 120)
    owner.widget_title_font_spin.setValue(28)
    owner.widget_body_font_spin = QSpinBox()
    owner.widget_body_font_spin.setRange(6, 120)
    owner.widget_body_font_spin.setValue(22)
    owner.widget_detail_font_spin = QSpinBox()
    owner.widget_detail_font_spin.setRange(6, 120)
    owner.widget_detail_font_spin.setValue(18)
    owner.widget_title_color_edit = QLineEdit()
    owner.widget_body_color_edit = QLineEdit()
    owner.widget_detail_color_edit = QLineEdit()
    owner.widget_panel_color_edit = QLineEdit()
    owner.widget_cover_enabled_chk = QCheckBox("Cover")
    owner.widget_cover_enabled_chk.setChecked(True)
    owner.widget_backdrop_enabled_chk = QCheckBox("Cover backdrop")
    owner.widget_backdrop_enabled_chk.setChecked(True)
    owner.widget_title_marquee_chk = QCheckBox("Title marquee")
    owner.widget_title_marquee_chk.setChecked(True)
    owner.widget_equalizer_enabled_chk = QCheckBox("EQ")
    owner.widget_equalizer_enabled_chk.setChecked(True)

    owner.weather_widget_title_font_spin = QSpinBox()
    owner.weather_widget_title_font_spin.setRange(6, 120)
    owner.weather_widget_title_font_spin.setValue(18)
    owner.weather_widget_body_font_spin = QSpinBox()
    owner.weather_widget_body_font_spin.setRange(6, 120)
    owner.weather_widget_body_font_spin.setValue(38)
    owner.weather_widget_detail_font_spin = QSpinBox()
    owner.weather_widget_detail_font_spin.setRange(6, 120)
    owner.weather_widget_detail_font_spin.setValue(18)
    owner.weather_widget_title_color_edit = QLineEdit()
    owner.weather_widget_body_color_edit = QLineEdit()
    owner.weather_widget_detail_color_edit = QLineEdit()
    owner.weather_widget_panel_color_edit = QLineEdit()
    owner.weather_widget_transparent_bg_chk = QCheckBox("Transparent background")
    owner.weather_widget_animate_icons_chk = QCheckBox("Animated icons")
    owner.weather_widget_animate_icons_chk.setChecked(True)

    owner.designer_theme_gauge_style_combo = QComboBox()
    owner._populate_designer_theme_gauge_style_combo()
    owner.designer_font_bold_chk = QCheckBox("B")
    owner.designer_font_italic_chk = QCheckBox("I")
    owner.designer_font_underline_chk = QCheckBox("U")

    owner.designer_path_edit = QLineEdit()
    owner.designer_fit_combo = QComboBox()
    owner.designer_fit_combo.addItems(["contain", "cover", "stretch"])
    owner.designer_visible_chk = QCheckBox("Visible")
    owner.designer_locked_chk = QCheckBox("Locked")

    owner.designer_mode_combo = QComboBox()
    owner.designer_mode_combo.addItems(["Simple", "Advanced"])
    owner.designer_auto_preview_chk = QCheckBox("Auto-preview")
    owner.designer_auto_preview_chk.setChecked(True)
    owner.designer_snap_chk = QCheckBox("Snap")
    owner.designer_snap_chk.setChecked(True)
    owner.designer_snap_spin = QSpinBox()
    owner.designer_snap_spin.setRange(1, 128)
    owner.designer_snap_spin.setValue(8)
    owner.designer_undo_btn = QPushButton("Undo")
    owner.designer_redo_btn = QPushButton("Redo")
    owner.designer_animation_mode_btn = QPushButton("Animation")
    owner.designer_animation_mode_btn.setCheckable(True)
    owner.designer_assets_toggle_btn = QPushButton("Media")
    owner.designer_assets_toggle_btn.setCheckable(True)
    owner.designer_details_toggle_btn = QPushButton("Show bottom")
    owner.designer_details_toggle_btn.setCheckable(True)

    owner.motion_enabled_chk = QCheckBox("Animate element")
    owner.motion_start_spin = QSpinBox()
    owner.motion_start_spin.setRange(0, 99999)
    owner.motion_end_spin = QSpinBox()
    owner.motion_end_spin.setRange(0, 99999)
    owner.motion_target_x_spin = QSpinBox()
    owner.motion_target_x_spin.setRange(-5000, 5000)
    owner.motion_target_y_spin = QSpinBox()
    owner.motion_target_y_spin.setRange(-5000, 5000)
    owner.motion_target_opacity_spin = QDoubleSpinBox()
    owner.motion_target_opacity_spin.setRange(0.0, 1.0)
    owner.motion_target_opacity_spin.setSingleStep(0.05)
    owner.motion_capture_current_btn = QPushButton("Set end from current")
    owner.motion_remove_btn = QPushButton("Remove motion")
